# MulBrandEval — Phase 1C: Component Validation Script
# ══════════════════════════════════════════════════════════════════════════════
#
# Purpose:
#   Validates that each DAG node tool (GPT-4o mini VQA, EasyOCR) is capable
#   of measuring its target compliance dimension reliably, BEFORE running the
#   full multilingual evaluation in Phase 2A. This is a tool-calibration step,
#   not an evaluation of generated images.
#
# Nodes (in execution order):
#   Node 1 — Object Presence    GPT-4o mini VQA   MS-COCO val2017       F1 >= 0.80
#   Node 2 — Spatial Layout     GPT-4o mini VQA   PaintSkills spatial    Acc >= 0.50
#   Node 3 — Attribute/Colour   BLIP-VQA + mCLIP  T2I-CompBench color    rho >= 0.60  [FAILED — kept as audit trail]
#   Node 3r— Attribute/Colour   GPT-4o mini VQA   T2I-CompBench color    rho >= 0.60  [recalibrated]
#   Node 4 — Typography         EasyOCR 1.7.1     DrawBench Text         Acc >= 0.75
#
# Usage:
#   python phase1c_agent_validation/phase1c_validate.py 1    -> Node 1 only
#   python phase1c_agent_validation/phase1c_validate.py 2    -> Node 2 only
#   python phase1c_agent_validation/phase1c_validate.py 3    -> Node 3 original (mCLIP, audit trail)
#   python phase1c_agent_validation/phase1c_validate.py 3r   -> Node 3 recalibrated (GPT-4o mini)
#   python phase1c_agent_validation/phase1c_validate.py 4    -> Node 4 only
#   python phase1c_agent_validation/phase1c_validate.py      -> all nodes in sequence
#
# Notes:
#   - Run '3' before '3r': recalibrated Node 3 needs BLIP scores from the
#     original run as its reference signal.
#   - Node 3 images must be pre-generated by phase1c_generate.py before
#     running nodes 3 or 3r.
#   - Node 2 downloads PaintSkills images on first run; they are cached
#     locally to data/reference_images/paintskills_node2/ on subsequent runs.
#   - All results accumulate in results/phase1c/ — individual node CSVs,
#     component_validation_table.csv, and phase1c_summary.txt.
