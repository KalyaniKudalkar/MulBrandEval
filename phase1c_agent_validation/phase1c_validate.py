            results.append({
                "prompt_id":   p["prompt_id"], "model": model_key,
                "prompt_text": p["text"],      "color_pairs": str(pairs),
                "blip_score":  round(blip_s, 4),
                "mclip_score": round(mclip_s, 4), "image_found": 1
            })

