# NODE 2 — Spatial Layout Validation
#
# Goal:   Confirm GPT-4o mini VQA can correctly identify spatial relations
#         between objects (left/right/front/behind), the signal used in
#         Phase 2A to score spatial compliance.
#
# Method: Sample 30 scenes from PaintSkills spatial_val split (seed 42).
#         For each scene, ask GPT-4o mini two balanced yes/no questions:
#           - Positive: Is [obj1] to the [correct direction] of [obj0]?  (GT = YES)
#           - Negative: Is [obj1] to the [opposite direction] of [obj0]? (GT = NO)
#         This balanced design prevents always-yes / always-no bias.
#
# Dataset: j-min/PaintSkills on HuggingFace, spatial_val split (2700 entries).
#          Images are 720×720 synthetic PNG renders. Downloaded and cached
#          locally on first run.
#
# Dataset structure:
#   scenes['data'][i]['id']              -> 'spatial_val_00042'
#   scenes['data'][i]['text']            -> 'a dog is left to a car'
#   scenes['data'][i]['objects'][0]      -> reference object  (relation = None)
#   scenes['data'][i]['objects'][1]      -> positioned object (relation = 'left_0')
#   image filename                       -> image_spatial_val_00042.png
#
# Metric:  Spatial relation accuracy across all 60 binary queries.
# Target:  Accuracy >= 0.50 (better than random chance for left/right)
#
# Note on metric change: The exposé specified IoU vs DETR bounding boxes.
# Since Phase 1C uses GPT-4o mini VQA throughout (no bbox detector available),
# spatial relation accuracy replaces IoU. The threshold (>= 0.50) is preserved.
# This deviation is documented in the component validation table.
# ══════════════════════════════════════════════════════════════════════════════

def run_node2():
    from huggingface_hub import hf_hub_download
    import shutil

    print("=" * 65)
    print("NODE 2 — Spatial Layout Validation")
    print("=" * 65)

    # ── Load PaintSkills scenes JSON ──────────────────────────────────────────
    # The JSON has a single top-level key 'data' containing a list of 2700 dicts.
    # Each dict has: id, text, scene, skill, split, objects[]
    print("\n  Loading PaintSkills spatial_val.json from HuggingFace...")
    scenes_path = hf_hub_download(
        'j-min/PaintSkills',
        'spatial/scenes/spatial_val.json',
        repo_type='dataset'
    )
    with open(scenes_path, 'r', encoding='utf-8') as f:
        scenes_json = json.load(f)

    scenes = scenes_json['data']
    print(f"  Total scenes loaded: {len(scenes)}")

    # ── Sample 30 scenes (seed 42) ────────────────────────────────────────────
    # Use a local Random instance (not the global one) so this sampling
    # is reproducible and independent of call order in the 'all' run.
    N_SAMPLE = 30
    rng      = random.Random(SEED)
    sampled  = rng.sample(scenes, N_SAMPLE)
    print(f"  Sampled {N_SAMPLE} scenes with seed {SEED}")
    print("  Sample IDs (first 5):", [s['id'] for s in sampled[:5]], "...")

    # ── Opposite-direction lookup ─────────────────────────────────────────────
    # Used to construct the negative (wrong-direction) question for each scene.
    OPPOSITE = {
        'left':   'right',
        'right':  'left',
        'above':  'below',   # added: PaintSkills spatial_val includes above/below relations
        'below':  'above',   # added: confirmed from node2 run (12/30 scenes were above/below)
        'front':  'behind',
        'behind': 'front',
    }

    # ── Local image cache ─────────────────────────────────────────────────────
    # Images are downloaded from HuggingFace and cached locally so that
    # re-runs (e.g. retries after a GPT error) do not re-download.
    PAINTSKILLS_CACHE_DIR.mkdir(parents=True, exist_ok=True)

    def get_image(scene_id: str) -> Path:
        """
        Return local path to a PaintSkills image, downloading from HuggingFace
        if not already cached.
        scene_id example: 'spatial_val_00042'
        filename example: 'image_spatial_val_00042.png'
        """
        filename   = f"image_{scene_id}.png"
        local_path = PAINTSKILLS_CACHE_DIR / filename
        if not local_path.exists():
            hf_path    = f"spatial/val_images/{filename}"
            downloaded = hf_hub_download(
                'j-min/PaintSkills', hf_path, repo_type='dataset'
            )
            shutil.copy(downloaded, local_path)
        return local_path

    def query_spatial(image_path: Path, obj0: str, obj1: str,
                      direction: str, retries: int = 3) -> int:
        """
        Ask GPT-4o mini: 'Is the [obj1] to the [direction] of the [obj0]?'
        Returns 1 (yes) or 0 (no). Uses detail=low for cost and consistency
        with Node 1 / Node 3r. Retries up to 3 times on API errors.
        """
        with open(image_path, "rb") as f:
            b64 = base64.b64encode(f.read()).decode("utf-8")

        question = (
            f"In this image, is the {obj1} positioned to the {direction} "
            f"of the {obj0}? Answer with only 'yes' or 'no'."
        )

        for attempt in range(retries):
            try:
                response = client.chat.completions.create(
                    model="gpt-4o-mini",
                    messages=[{
                        "role": "user",
                        "content": [
                            {"type": "image_url",
                             "image_url": {
                                 "url": f"data:image/png;base64,{b64}",
                                 "detail": "low"
                             }},
                            {"type": "text", "text": question}
                        ]
                    }],
                    max_tokens=5,
                    temperature=0
                )
                answer = response.choices[0].message.content.strip().lower()
                return 1 if answer.startswith("yes") else 0
            except Exception as e:
                print(f"    Retry {attempt + 1}/3 ({direction}): {e}")
                time.sleep(3)
        return 0   # conservative default on persistent failure

    # ── Run balanced spatial VQA ──────────────────────────────────────────────
    results       = []
    total_correct = 0
    total_queries = 0

    print(f"\n  Running VQA: {N_SAMPLE} scenes × 2 questions = {N_SAMPLE * 2} GPT-4o mini calls")
    print("  (detail=low; ~$0.003 estimated cost)\n")

    for i, scene in enumerate(sampled):
        scene_id     = scene['id']                          # e.g. 'spatial_val_00042'
        text         = scene['text']                        # e.g. 'a dog is left to a car'
        obj0         = scene['objects'][0]['coconame']      # reference object (relation=None)
        obj1         = scene['objects'][1]['coconame']      # positioned object (has relation)
        relation_raw = scene['objects'][1]['relation']      # e.g. 'left_0'
        direction    = relation_raw.split('_')[0]          # e.g. 'left'
        opposite     = OPPOSITE.get(direction, 'right')    # e.g. 'right'

        # Download image, cached after first run
        try:
            img_path = get_image(scene_id)
        except Exception as e:
            print(f"  [{i + 1:2d}/{N_SAMPLE}] DOWNLOAD FAILED {scene_id}: {e} — skipping")
            continue

        # Positive question: correct direction — ground truth = YES (expect pred=1)
        pred_pos = query_spatial(img_path, obj0, obj1, direction)
        corr_pos = int(pred_pos == 1)
        time.sleep(0.4)

        # Negative question: opposite direction — ground truth = NO (expect pred=0)
        pred_neg = query_spatial(img_path, obj0, obj1, opposite)
        corr_neg = int(pred_neg == 0)
        time.sleep(0.4)

        total_correct += corr_pos + corr_neg
        total_queries += 2

        print(f"  [{i + 1:2d}/{N_SAMPLE}] {scene_id} | "
              f"'{obj1} {direction} {obj0}' | "
              f"pos={'HIT' if corr_pos else 'MISS'}  "
              f"neg={'HIT' if corr_neg else 'MISS'}")

        results.append({
            "scene_id":         scene_id,
            "text":             text,
            "obj0":             obj0,
            "obj1":             obj1,
            "direction":        direction,
            "opposite":         opposite,
            "pred_positive":    pred_pos,    # 1=yes, 0=no (GT should be 1)
            "pred_negative":    pred_neg,    # 1=yes, 0=no (GT should be 0)
            "correct_positive": corr_pos,
            "correct_negative": corr_neg,
        })

    # ── Save per-scene results ────────────────────────────────────────────────
    results_df = pd.DataFrame(results)
    results_df.to_csv(NODE2_CSV, index=False, encoding='utf-8')
    print(f"\n  Detailed results saved: {NODE2_CSV}  ({len(results_df)} rows)")

    # ── Compute accuracy ──────────────────────────────────────────────────────
    accuracy  = total_correct / total_queries if total_queries > 0 else 0.0
    TARGET    = 0.50
    pass_fail = "PASS" if accuracy >= TARGET else "FAIL"
    threshold = (
        "GPT-4o mini spatial direction VQA | "
        "'Is [obj1] to the [direction] of [obj0]?' binary yes/no | "
        "balanced pos/neg questions | detail=low"
    )

    print("\n" + "-" * 45)
    print(f"  Total queries  : {total_queries}")
    print(f"  Correct        : {total_correct}")
    print(f"  Accuracy       : {accuracy:.4f}  (target >= {TARGET})")
    print(f"  Status         : {pass_fail}")
    print("-" * 45)

    if pass_fail == "FAIL":
        print("\n  NOTE: Accuracy below target (>= 0.50 = better than random).")
        print("  Assess whether this is a GPT-4o mini limitation at detail=low")
        print("  or a genuine spatial reasoning gap.")

    # ── Update component validation table ────────────────────────────────────
    table_row = {
        "node":       "Node 2",
        "capability": "Spatial Layout",
        "tool":       "GPT-4o mini VQA",
        "dataset":    (f"PaintSkills spatial_val "
                       f"(n={len(results_df)} scenes, {total_queries} queries)"),
        "metric":     "Spatial relation accuracy (binary yes/no, balanced pos/neg)",
        "score":      round(accuracy, 4),
        "target":     f">= {TARGET}",
        "pass_fail":  pass_fail,
        "evaluation_method": threshold,
    }
    write_header = not VALIDATION_TABLE.exists()
    with open(VALIDATION_TABLE, "a", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(table_row.keys()))
        if write_header:
            writer.writeheader()
        writer.writerow(table_row)
    print(f"\n  Component validation table updated: {VALIDATION_TABLE}")

    # ── Append one-liner to summary txt ──────────────────────────────────────
    node2_summary = (
        f"Node 2 | Spatial Layout | GPT-4o mini VQA | "
        f"Accuracy={accuracy:.4f} | target>={TARGET} | {pass_fail} | "
        f"correct={total_correct}/{total_queries} | "
        f"metric=spatial_relation_accuracy "
        f"(expose specified IoU; replaced by VQA direction test — "
        f"IoU requires bbox detector not available in VQA pipeline)\n"
    )
    with open(SUMMARY_TXT, "a", encoding="utf-8") as fh:
        fh.write(node2_summary)

    print(f"  Summary written: {SUMMARY_TXT}")
    print("\nNode 2 validation complete.")
    return accuracy, pass_fail


